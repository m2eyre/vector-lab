// Bundles the runtime-agnostic server into one ES module for the Supabase Edge Function.
import { build } from 'esbuild';
import { builtinModules } from 'node:module';

const builtins = new Set(builtinModules.flatMap((m) => [m, `node:${m}`]));
await build({
  entryPoints: ['server/edge-entry.ts'],
  outfile: 'supabase/functions/api/server.bundle.js',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['deno', 'worker', 'import'],
  legalComments: 'none',
  // Supabase's Edge runtime does not define the Node globals that postgres.js uses (Buffer,
  // process, setImmediate, clearImmediate). Provide them from Deno's Node compatibility modules.
  banner: { js: [
    '// GENERATED by `npm run build:edge`. Do not edit.',
    'import { Buffer as __vlBuffer } from "node:buffer";',
    'import __vlProcess from "node:process";',
    'import { setImmediate as __vlSetImmediate, clearImmediate as __vlClearImmediate } from "node:timers";',
    'globalThis.Buffer ??= __vlBuffer;',
    'globalThis.process ??= __vlProcess;',
    'globalThis.setImmediate ??= __vlSetImmediate;',
    'globalThis.clearImmediate ??= __vlClearImmediate;',
    'globalThis.global ??= globalThis;',
  ].join('\n') },
  plugins: [{
    name: 'node-builtins',
    setup(b) {
      // Deno needs Node built-ins to be imported with the node: prefix.
      b.onResolve({ filter: /.*/ }, (args) => (builtins.has(args.path) ? { path: args.path.startsWith('node:') ? args.path : `node:${args.path}`, external: true } : null));
    },
  }],
});
console.log('built supabase/functions/api/server.bundle.js');
